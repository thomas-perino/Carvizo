/**
 * Données de démonstration : 15 annonces FICTIVES mais réalistes.
 *
 * ⚠️ Ces annonces ne correspondent à aucun véhicule réellement en vente.
 * Elles servent uniquement à peupler l'application pendant cette étape de
 * fondation. Elles ne doivent jamais être présentées comme des annonces
 * réelles actuellement disponibles (voir badge "DEMO" partout dans l'UI).
 *
 * Depuis l'introduction du Market Value Engine (lib/market-value/), ce
 * fichier n'autorise plus de valeur de marché saisie à la main :
 * `generation`, `trim`, `condition` et `options` décrivent le véhicule
 * cible, et c'est `data/demo/comparables.ts` (+ le moteur) qui produit la
 * valeur de marché. Seuls les prix de revente (scénarios prudent/réaliste/
 * optimiste), qui relèvent d'une décision commerciale future et non de la
 * valeur de marché actuelle, restent saisis à la main à ce stade.
 */

export interface DemoSeed {
  externalId: string;
  make: string;
  model: string;
  /** Génération/plateforme, utilisée par le Market Value Engine pour affiner les comparables. */
  generation?: string;
  version: string;
  /** Finition commerciale (voir lib/market-value/adjustments.ts). */
  trim?: string;
  year: number;
  mileage: number;
  fuelTypeRaw: string;
  transmissionRaw: string;
  horsepower: number;
  fiscalPower: number;
  location: string;
  sellerTypeRaw: string;
  condition: VehicleCondition;
  /** Équipements significatifs reconnus par OptionAdjustmentProvider. */
  options?: string[];
  price: number;
  description: string;
  images: string[];
  publishedAt: string;
  retrievedAt: string;

  resalePriceConservative: number;
  resalePriceRealistic: number;
  resalePriceOptimistic: number;
  transportCost: number;
  preparationCost: number;
  repairs: RepairSignal[];
  resaleEaseScore: number;
  accidentReported: boolean;

  /** Étiquette du profil pédagogique illustré (voir spec §8), affichée nulle part
   * dans l'UI publique mais utile pour les tests et la documentation. */
  profile: string;
}

function img(id: string, n: number): string[] {
  return Array.from({ length: n }, (_, i) => `https://picsum.photos/seed/carvizo-${id}-${i}/900/600`);
}

